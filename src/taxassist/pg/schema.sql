-- 由 SQLite 真实 DDL 转换而来
-- 顺序固定为 表 -> 索引 -> 视图（索引引用表，必须后置）

-- ===== 表 =====
CREATE TABLE api_key (
            key_hash     TEXT PRIMARY KEY,          -- sha256(明文)，不存明文
            customer     TEXT NOT NULL,
            label        TEXT,
            created_at   TEXT NOT NULL,
            last_used_at TEXT,
            revoked      BIGINT NOT NULL DEFAULT 0
        );
CREATE TABLE app_user (
    username      TEXT PRIMARY KEY,
    password_hash TEXT NOT NULL,
    created_at    TEXT NOT NULL,
    last_login_at TEXT,
    login_count   BIGINT NOT NULL DEFAULT 0
, role TEXT NOT NULL DEFAULT 'member');
CREATE TABLE attachment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_uid       TEXT NOT NULL,
    url           TEXT,
    filename      TEXT,
    ext           TEXT,
    raw_path      TEXT,                -- 下载后的本地路径
    parsed_text   TEXT,                -- PDF/Excel 解析出的文本
    parse_status  TEXT DEFAULT 'pending',  -- pending/ok/failed
    parse_error   TEXT,
    created_at    TEXT NOT NULL,
    claimed_at    TEXT,
    UNIQUE(doc_uid, url)
);
CREATE TABLE customer (
            name              TEXT PRIMARY KEY,
            note              TEXT,
            balance           BIGINT NOT NULL DEFAULT 0,  -- 检索次数余额
            assistant_balance BIGINT NOT NULL DEFAULT 0,  -- 助手次数余额
            active            BIGINT NOT NULL DEFAULT 1,
            created_at        TEXT NOT NULL
        , unlimited BIGINT NOT NULL DEFAULT 0);
CREATE TABLE fetch_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id       TEXT NOT NULL,
    mode            TEXT NOT NULL,     -- full / incremental / probe
    started_at      TEXT NOT NULL,
    finished_at     TEXT,
    window_start    TEXT,
    window_end      TEXT,
    reported_total  BIGINT,           -- 接口声称的总数
    fetched_count   BIGINT,           -- 实际抓到条数
    new_count       BIGINT DEFAULT 0,
    updated_count   BIGINT DEFAULT 0,
    status          TEXT,              -- ok / incomplete / failed
    error           TEXT
, skipped_count BIGINT, unchanged_count BIGINT);
CREATE TABLE invite_code (
    code       TEXT PRIMARY KEY,
    created_at TEXT NOT NULL,
    expires_at TEXT,
    used_by    TEXT,
    used_at    TEXT,
    note       TEXT,
    revoked    BIGINT NOT NULL DEFAULT 0
, grants_role TEXT NOT NULL DEFAULT 'member');
CREATE TABLE meta (
    key         TEXT PRIMARY KEY,
    value       TEXT,
    updated_at  TEXT NOT NULL
);
CREATE TABLE policy (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_uid            TEXT NOT NULL UNIQUE,   -- 官方 id（跨系统稳定标识）
    url                TEXT,                   -- 详情页
    snapshot_url       TEXT,                   -- 官方快照页
    url_md5            TEXT,                   -- 官方 urlMD5

    title              TEXT NOT NULL,
    second_title       TEXT,
    o_column           TEXT,                   -- 栏目：政策法规/政策解读/政策指引
    o_label            TEXT,                   -- 标签：法律/行政法规/税务规范性文件/财税文件…
    o_typename         TEXT,
    o_site_name        TEXT,

    cwrq               TEXT,                   -- 成文日期 YYYY-MM-DD
    pub_date           TEXT,                   -- 发布日期 YYYY-MM-DD
    o_abolish_date     TEXT,                   -- 官方废止日期（若有）

    o_doc_no_raw       TEXT,                   -- 官方 docNo —— 注意：实测只是序号
    o_doc_num          TEXT,                   -- 官方 docNum
    o_doc_type         TEXT,
    o_doc_year         TEXT,
    p_doc_no_full      TEXT,                   -- 本系统拼接的完整文号
    p_doc_no_confidence TEXT,                  -- high/medium/low

    pub_name           TEXT,                   -- 发文机关
    o_file_type        TEXT,                   -- 官方 xxgk_effectLevel（实测是文件类型）
    o_aging            TEXT,                   -- 官方 xxgk_aging（真实时效标注，常为空）
    o_tax_policy       TEXT,
    o_tax_discount     TEXT,
    o_industry_type    TEXT,
    o_taxpayer_type    TEXT,
    o_policy_file_type TEXT,
    o_revise_type      TEXT,
    o_resolve_type     TEXT,
    o_related_policy   TEXT,                   -- 官方"相关文件"名称
    o_keywords         TEXT,
    o_industries       TEXT,

    content            TEXT,                   -- 正文（API 返回）
    zw_content         TEXT,                   -- 正文（政务版）
    short_content      TEXT,

    -- 本地效力判定
    p_effect_status    TEXT DEFAULT 'unknown', -- 现行有效/已废止/部分失效/尚未生效/未知
    p_effect_source    TEXT DEFAULT 'none',    -- official/inferred/manual
    p_effect_reason    TEXT,                   -- 判定理由（人可读）
    p_effect_evidence  TEXT,                   -- 证据原文片段
    p_review_state     TEXT DEFAULT 'auto',    -- auto/needs_review/confirmed

    content_hash       TEXT,
    first_seen_at      TEXT NOT NULL,
    last_seen_at       TEXT NOT NULL,
    last_changed_at    TEXT,
    fetch_count        BIGINT NOT NULL DEFAULT 1
, p_effective_date TEXT, p_detail_fetched_at TEXT, p_region TEXT, p_translated_at TEXT, is_official BIGINT NOT NULL DEFAULT 1, p_doc_no_year BIGINT, p_doc_no_seq BIGINT);
CREATE TABLE policy_relation (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src_doc_uid    TEXT NOT NULL,          -- 引用方（"谁说的"）
    dst_doc_uid    TEXT,                   -- 被引用方（已入库时）
    dst_doc_no     TEXT,                   -- 被引用文号（文本，可能尚未入库）
    relation       TEXT NOT NULL,          -- cites/repeals/amends/supersedes/related
    evidence       TEXT,                   -- 证据原文片段
    evidence_source TEXT,                  -- official_field/title/content/manual
    confidence     TEXT DEFAULT 'low',     -- high/medium/low
    created_at     TEXT NOT NULL,
    UNIQUE(src_doc_uid, dst_doc_uid, dst_doc_no, relation)
);
CREATE TABLE raw_snapshot (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_uid       TEXT,
    source_id     TEXT NOT NULL,
    fetched_at    TEXT NOT NULL,
    http_url      TEXT NOT NULL,
    kind          TEXT NOT NULL,      -- api_json / detail_html / attachment_pdf
    rel_path      TEXT,               -- 相对 RAW_DIR 的归档路径
    content_hash  TEXT,
    size_bytes    BIGINT,
    UNIQUE(doc_uid, kind, content_hash)
);
CREATE TABLE translation ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, doc_uid TEXT NOT NULL, field TEXT NOT NULL, lang TEXT NOT NULL DEFAULT 'en', src_hash TEXT NOT NULL, text TEXT NOT NULL, model TEXT, created_at TEXT NOT NULL, UNIQUE(doc_uid, field, lang));
CREATE TABLE translation_ai_review ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, doc_uid TEXT NOT NULL, field TEXT NOT NULL, verdict TEXT NOT NULL, reason TEXT, model TEXT, zh_len BIGINT, reviewed_at TEXT NOT NULL, UNIQUE(doc_uid, field));
CREATE TABLE translation_review ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, doc_uid TEXT NOT NULL, field TEXT NOT NULL, verdict TEXT NOT NULL, note TEXT, reviewer TEXT, kind TEXT, reviewed_at TEXT NOT NULL, UNIQUE(doc_uid, field));
CREATE TABLE usage_log (
            id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ts       TEXT NOT NULL,
            customer TEXT NOT NULL,
            kind     TEXT NOT NULL,
            ok       BIGINT NOT NULL,
            cost     BIGINT NOT NULL DEFAULT 0,
            detail   TEXT
        );

-- ===== 索引 =====
CREATE INDEX idx_attach_status ON attachment(parse_status);
CREATE INDEX idx_fetchlog_source ON fetch_log(source_id, started_at DESC);
CREATE INDEX idx_policy_column      ON policy(o_column);
CREATE INDEX idx_policy_cwrq        ON policy(cwrq DESC);
CREATE INDEX idx_policy_docno       ON policy(p_doc_no_full);
CREATE INDEX idx_policy_effect      ON policy(p_effect_status);
CREATE INDEX idx_policy_effsrc ON policy(p_effect_status, p_effect_source);
CREATE INDEX idx_policy_pubdate     ON policy(pub_date DESC);
CREATE INDEX idx_policy_region ON policy(p_region);
CREATE INDEX idx_policy_review      ON policy(p_review_state);
CREATE INDEX idx_policy_urumd5      ON policy(url_md5);
CREATE INDEX idx_raw_docuid ON raw_snapshot(doc_uid);
CREATE INDEX idx_rel_dst ON policy_relation(dst_doc_uid);
CREATE INDEX idx_rel_dstno ON policy_relation(dst_doc_no);
CREATE INDEX idx_rel_src ON policy_relation(src_doc_uid);
CREATE INDEX idx_usage_customer_ts
            ON usage_log(customer, ts);

-- ===== 视图 =====
CREATE VIEW policy_official AS SELECT * FROM policy WHERE COALESCE(is_official, 1) = 1;
